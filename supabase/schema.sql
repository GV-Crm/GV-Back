-- ---------- Catálogo de estados de asistencia ----------
create table public."EstadosAsistencia" (
  id bigint generated by default as identity primary key,
  "Motivo" text not null
);

-- ---------- Áreas de la empresa ----------
create table public."Areas" (
  id bigint generated always as identity primary key,
  "Nombre" text not null,
  "CreadoEn" timestamptz not null default now(),
  constraint "Areas_Nombre_check" check ("Nombre" = btrim("Nombre", E' \t\r\n') and length("Nombre") between 1 and 60)
);
create unique index "Areas_Nombre_unico" on public."Areas" (lower("Nombre"));
comment on table public."Areas" is 'Áreas de la empresa. Se agregan desde Trabajadores → Áreas; Empleados.Area guarda el nombre.';

-- ---------- Trabajadores ----------
-- ID del trabajador en el checador (lo genera la base, empieza en 1001 y nunca se repite).
create sequence public."Empleados_PinChecador_seq" start 1001;

create table public."Empleados" (
  id bigint generated by default as identity primary key,
  "Nombre" text not null,
  "Area" text,
  "Uuid" uuid default gen_random_uuid(),
  "Activo" boolean,
  "Ingreso" date,
  "Foto" text,
  "PinChecador" integer not null default nextval('public."Empleados_PinChecador_seq"'),
  constraint "Empleados_PinChecador_key" unique ("PinChecador")
);
alter sequence public."Empleados_PinChecador_seq" owned by public."Empleados"."PinChecador";

comment on column public."Empleados"."Foto" is 'URL pública de la foto del trabajador (bucket avatares, archivo empleado-<id>.webp).';
comment on column public."Empleados"."PinChecador" is 'ID del trabajador en el checador (lo genera la base). Las marcas del checador traen este número como PIN.';

-- ---------- Asistencias (registros capturados y faltas guardadas) ----------
create table public."Asistencias" (
  id bigint generated by default as identity primary key,
  id_empleados bigint references public."Empleados"(id),
  "HoraEntrada" timestamptz,
  "HoraSalida" timestamptz,
  id_estado bigint references public."EstadosAsistencia"(id),
  "InicioComida" timestamptz,
  "FinComida" timestamptz,
  "Fecha" date,
  "Justificacion" text,
  "JustificadoPor" text
);
create unique index "Asistencias_falta_unica_por_dia" on public."Asistencias" (id_empleados, "Fecha")
  where ("HoraEntrada" is null and "Fecha" is not null);

comment on column public."Asistencias"."Fecha" is 'Día de una falta generada por el sistema (esas filas no tienen HoraEntrada).';
comment on column public."Asistencias"."Justificacion" is 'Motivo escrito al marcar una falta como justificada.';
comment on column public."Asistencias"."JustificadoPor" is 'Nombre (o correo) de quien justificó la falta.';

-- ---------- Datos personales (sensibles, 1 a 1 con Empleados) ----------
create table public."DatosPersonales" (
  id_empleados bigint primary key references public."Empleados"(id) on delete cascade,
  "FechaNacimiento" date,
  "Celular" text,
  "Correo" text,
  "CURP" text,
  "RFC" text,
  "NSS" text,
  "Domicilio" text,
  "ContactosEmergencia" jsonb not null default '[]'::jsonb,
  "ActualizadoEn" timestamptz not null default now(),
  "ActualizadoPor" text,
  "SalarioDiario" numeric(10, 2) check ("SalarioDiario" > 0)
);
-- Un CURP, RFC o NSS solo puede pertenecer a un trabajador.
create unique index "DatosPersonales_CURP_key" on public."DatosPersonales" ("CURP") where "CURP" is not null;
create unique index "DatosPersonales_RFC_key" on public."DatosPersonales" ("RFC") where "RFC" is not null;
create unique index "DatosPersonales_NSS_key" on public."DatosPersonales" ("NSS") where "NSS" is not null;

comment on table public."DatosPersonales" is 'Datos personales de cada trabajador (1 a 1 con Empleados).';
comment on column public."DatosPersonales"."ContactosEmergencia" is 'Lista de { Nombre, Parentesco, Telefono } (máximo 3).';
comment on column public."DatosPersonales"."ActualizadoPor" is 'Correo de la cuenta que hizo el último cambio.';
comment on column public."DatosPersonales"."SalarioDiario" is 'Salario diario en pesos, para calcular la prima vacacional.';

-- ---------- Vacaciones (días seguidos o salteados) ----------
create table public."Vacaciones" (
  id bigint generated always as identity primary key,
  id_empleados bigint not null references public."Empleados"(id) on delete cascade,
  "Desde" date not null,
  "Hasta" date not null,
  "Dias" smallint not null check ("Dias" > 0),
  "Nota" text,
  "RegistradoPor" text,
  "RegistradoEn" timestamptz not null default now(),
  "Fechas" date[] not null,
  constraint "Vacaciones_check" check ("Hasta" >= "Desde"),
  constraint "Vacaciones_Dias_igual_a_Fechas" check ("Dias" = cardinality("Fechas"))
);
create index "Vacaciones_empleado_fechas" on public."Vacaciones" (id_empleados, "Desde", "Hasta");

comment on table public."Vacaciones" is 'Solicitudes de vacaciones (días seguidos o salteados). En el calendario esos días son "vacaciones", no falta.';
comment on column public."Vacaciones"."Desde" is 'Primer día de "Fechas".';
comment on column public."Vacaciones"."Hasta" is 'Último día de "Fechas".';
comment on column public."Vacaciones"."Dias" is 'Cuántos días tiene "Fechas": los que se descuentan de su saldo.';
comment on column public."Vacaciones"."RegistradoPor" is 'Correo de la cuenta que registró el periodo.';
comment on column public."Vacaciones"."Fechas" is 'Días exactos de vacaciones (laborables, sin repetir, en orden). Pueden ser salteados.';

-- ---------- Permisos para salir antes (ventana de 10 min para checar) ----------
create table public."PermisosSalida" (
  id bigint generated always as identity primary key,
  id_empleados bigint not null references public."Empleados"(id) on delete cascade,
  "Fecha" date not null,
  "AutorizadoEn" timestamptz not null default now(),
  "VenceEn" timestamptz not null,
  "Motivo" text,
  "AutorizadoPor" text,
  constraint "PermisosSalida_ventana" check ("VenceEn" > "AutorizadoEn")
);
create index "PermisosSalida_empleado_fecha" on public."PermisosSalida" (id_empleados, "Fecha");
comment on table public."PermisosSalida" is 'Permisos para salir antes: la checada dentro de la ventana (AutorizadoEn a VenceEn) es su salida.';

-- ---------- Cuentas y permisos ----------
-- Cada cuenta de GV One: su correo (el de Supabase Auth) y su rol. El rol "Admin" puede todo.
create table public."Roles" (
  id bigint generated by default as identity primary key,
  "Uuid" uuid default gen_random_uuid(),
  "Nombre" text,
  "Rol" text not null,
  "Correo" text,
  "Avatar" text
);
comment on column public."Roles"."Avatar" is 'URL pública de la foto de perfil de la cuenta (bucket avatares).';

create table public."PermisosRol" (
  id bigint generated always as identity primary key,
  "Rol" text not null,
  "Accion" text not null,
  "Recurso" text not null,
  constraint "PermisosRol_unico" unique ("Rol", "Accion", "Recurso")
);
comment on table public."PermisosRol" is 'Qué puede hacer cada rol (Roles.Rol): una fila por acción sobre un recurso. El rol Admin tiene acceso total y no se guarda aquí.';

-- ---------- Checador ZKTeco (ADMS) ----------
create table public."Checadores" (
  id bigint generated always as identity primary key,
  "SN" text not null,
  "Nombre" text,
  "Autorizado" boolean not null default false,
  "UltimaConexion" timestamptz,
  "IP" text,
  "Info" text,
  "CreadoEn" timestamptz not null default now(),
  constraint "Checadores_SN_key" unique ("SN")
);
comment on table public."Checadores" is 'Checadores ZKTeco conectados por ADMS. SN = número de serie del equipo.';
comment on column public."Checadores"."Info" is 'Texto que manda el equipo con su versión y conteos (parámetro INFO).';

create table public."MarcasChecador" (
  id bigint generated always as identity primary key,
  "SN" text not null,
  "PIN" text not null,
  "FechaHora" timestamptz not null,
  "Estado" smallint,
  "Verificacion" smallint,
  "Linea" text,
  "RecibidoEn" timestamptz not null default now(),
  "Evento" smallint,
  "Indice" integer,
  constraint "MarcasChecador_unica" unique ("SN", "PIN", "FechaHora")
);
create index "MarcasChecador_fecha" on public."MarcasChecador" ("FechaHora" desc);

comment on table public."MarcasChecador" is 'Marcas crudas del checador. PIN = número del usuario en el equipo.';
comment on column public."MarcasChecador"."Estado" is '0 entrada, 1 salida, 2 inicio descanso, 3 fin descanso, 4 entrada extra, 5 salida extra. Null en control de acceso: el equipo no distingue entrada de salida.';
comment on column public."MarcasChecador"."Verificacion" is 'Cómo se identificó: 0 contraseña, 1 huella, 4 tarjeta, 15 rostro, 25 palma (según el equipo).';
comment on column public."MarcasChecador"."Evento" is 'Solo equipos de control de acceso (rtlog): código de evento del equipo. Observado: 3 = verificación correcta.';
comment on column public."MarcasChecador"."Indice" is 'Solo equipos de control de acceso (rtlog): consecutivo del registro dentro del equipo.';

-- ---------- Datos de la empresa (un solo renglón) ----------
create table public."Empresa" (
  id smallint primary key default 1 check (id = 1),
  "RazonSocial" text,
  "NombreComercial" text,
  "RFC" text,
  "RegimenFiscal" text,
  "RegistroPatronal" text,
  "DomicilioFiscal" text,
  "CodigoPostal" text,
  "Telefono" text,
  "Correo" text,
  "RepresentanteLegal" text,
  "ActualizadoEn" timestamptz,
  "ActualizadoPor" text,
  "PrimaVacacional" numeric(5, 2) not null default 25 check ("PrimaVacacional" >= 25 and "PrimaVacacional" <= 100)
);
comment on table public."Empresa" is 'Datos de la empresa: siempre un solo renglón (id = 1).';
comment on column public."Empresa"."RegistroPatronal" is 'Registro patronal ante el IMSS (11 caracteres).';
comment on column public."Empresa"."ActualizadoPor" is 'Correo de la cuenta que hizo el último cambio.';
comment on column public."Empresa"."PrimaVacacional" is 'Porcentaje de prima vacacional (mínimo 25% por el art. 80 de la LFT).';

-- ---------- Seguridad: RLS sin políticas (solo el backend con service_role) ----------
alter table public."Areas" enable row level security;
alter table public."EstadosAsistencia" enable row level security;
alter table public."Empleados" enable row level security;
alter table public."Asistencias" enable row level security;
alter table public."DatosPersonales" enable row level security;
alter table public."Vacaciones" enable row level security;
alter table public."PermisosSalida" enable row level security;
alter table public."Roles" enable row level security;
alter table public."PermisosRol" enable row level security;
alter table public."Checadores" enable row level security;
alter table public."MarcasChecador" enable row level security;
alter table public."Empresa" enable row level security;

